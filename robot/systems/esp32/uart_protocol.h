#pragma once
// Контракт последовательной линии Raspberry Pi <-> ESP32-C3.
//
// ЕДИНСТВЕННОЕ место, где записан формат: его подключает и драйвер привода на
// расбе (systems/rpi/drive), и прошивка (systems/esp32/firmware). Раньше формат
// был продублирован в обоих, и разойтись они могли молча -- робот просто ехал
// не туда. Меняешь формат здесь -- перешивай ESP и пересобирай робота вместе.
//
// Это внутренняя линия робота, поэтому она НЕ в common/: common описывает
// границу между двумя машинами (ноутбук <-> расба), а здесь обе стороны стоят
// на самом роботе.
//
// Заголовок обязан оставаться пригодным для Arduino: только целые типы и
// char-буферы, никакого <string>, никаких исключений.

namespace esp32_uart {

// Линия: 8N1, без управления потоком. ESP слушает UART1 (RX=GPIO20, TX=GPIO21).
constexpr int DEFAULT_BAUD = 115200;

// Команда привода: "R:<percent>%|L:<percent>%\n"
//   percent -- целое -100..100; плюс вперёд, минус назад, 0 стоп.
//   Завершитель обязателен: LF (CRLF прошивка тоже принимает).
constexpr int MIN_PERCENT = -100;
constexpr int MAX_PERCENT = 100;

// Самая длинная команда -- "R:-100%|L:-100%\n", 17 байт со скобкой под '\0'.
// Приёмный буфер прошивки такого же размера; более длинная строка отбрасывается
// целиком, а не режется на части.
constexpr int MAX_LINE_LENGTH = 32;

// Прошивка глушит оба мотора, если за это время не пришло ни одной корректной
// полной команды. Отправитель обязан повторять команду заметно чаще -- сейчас
// это делает каждый принятый кадр DesiredState, а в паузах связи heartbeat
// восстановления в control_loop.
constexpr int COMMAND_TIMEOUT_MS = 500;

// Телеметрия датчика звука, которую шлёт motor_driver раз в 100 мс:
//   "S:<0|1>|N:<counter>\n"
// Линия полнодуплексная, приём команд это не задерживает. Расба её сейчас не
// читает; формат описан здесь, чтобы контракт линии лежал в одном месте
// целиком, а не половиной.

}  // namespace esp32_uart
